    PRIMARY KEY (id),
    CONSTRAINT uk_roles_code UNIQUE (code)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE user_roles (
    id         BIGINT      NOT NULL AUTO_INCREMENT,
    user_id    BIGINT      NOT NULL,
    role_id    BIGINT      NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_user_roles_user_role UNIQUE (user_id, role_id),
    KEY idx_user_roles_role (role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- One-time codes sent by email for sign-up and for password recovery. There is no foreign key
-- to users, because a sign-up code exists before the user does. The code itself is stored
-- hashed. Rows are short-lived; the application account may insert and update them, not delete.
CREATE TABLE email_verification_codes (
    id          BIGINT       NOT NULL AUTO_INCREMENT,
    email       VARCHAR(254) NOT NULL,
    purpose     VARCHAR(32)  NOT NULL,
    code_hash   VARCHAR(255) NOT NULL,
    attempts    INT          NOT NULL DEFAULT 0,
    expires_at  DATETIME(3)  NOT NULL,
    consumed_at DATETIME(3)  NULL,
    created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_email_codes_lookup (email, purpose, created_at),
    CONSTRAINT chk_email_codes_purpose CHECK (purpose IN ('REGISTER', 'RESET_PASSWORD')),
    CONSTRAINT chk_email_codes_attempts CHECK (attempts >= 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- ---------------------------------------------------------------------------
-- Warehouse items, products, and listing events
-- ---------------------------------------------------------------------------

-- A warehouse item and its stock. It exists before it is ever sold, and it has one row for
-- the whole life of the item. name and image_url describe the item in the warehouse; the
-- image is optional and only helps the product page. created_at is the time the item entered
-- the warehouse, and created_by is who added it. Stock is changed only under pessimistic row
-- locking (SELECT ... FOR UPDATE), so this table has no version column.
-- sku is generated by the program: 8 characters from A-Z and 0-9, never chosen by a person.
-- An item is deleted softly, because orders, stock records, tickets, and events refer to it:
-- deleted_at and deleted_by are set, and the name becomes free again. The generated column
-- is_active is 1 while the item is not deleted and NULL afterwards, so UNIQUE (name, is_active)
-- keeps the names of the items in the warehouse unique and lets a deleted name be used again
-- (MySQL allows many NULLs in a unique key). The stock left on a deleted item no longer matters:
-- when the item is added again, a person counts the stock and enters it.
CREATE TABLE inventory (
    id                 BIGINT       NOT NULL AUTO_INCREMENT,
    sku                CHAR(8)      NOT NULL,
    name               VARCHAR(200) NOT NULL,
    image_url          VARCHAR(500) NULL,
    available_quantity INT          NOT NULL DEFAULT 0,
    sold_quantity      INT          NOT NULL DEFAULT 0,
    created_by         BIGINT       NOT NULL,
    created_at         DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at         DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    deleted_by         BIGINT       NULL,
    deleted_at         DATETIME(3)  NULL,
    is_active          TINYINT      GENERATED ALWAYS AS (IF(deleted_at IS NULL, 1, NULL)) STORED,
    PRIMARY KEY (id),
    CONSTRAINT uk_inventory_sku UNIQUE (sku),
    -- Also serves the catalog and the item list, which search by name.
    CONSTRAINT uk_inventory_name_active UNIQUE (name, is_active),
    KEY idx_inventory_created_by (created_by),
    KEY idx_inventory_deleted_by (deleted_by),
    CONSTRAINT fk_inventory_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_inventory_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_inventory_available CHECK (available_quantity >= 0),
    CONSTRAINT chk_inventory_sold CHECK (sold_quantity >= 0),
    CONSTRAINT chk_inventory_sku CHECK (REGEXP_LIKE(sku, '^[A-Z0-9]{8}$', 'c')),
    CONSTRAINT chk_inventory_deleted CHECK (
        (deleted_at IS NULL AND deleted_by IS NULL)
        OR (deleted_at IS NOT NULL AND deleted_by IS NOT NULL)
    )
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- Append-only record of every addition and deletion of a warehouse item: the item, the SKU and
-- name it had, the quantity (the starting stock when it was added, the stock it still showed when
-- it was deleted, for the record only), who did it, and when. It belongs to the inventory records and is separate from
-- the product records.
CREATE TABLE inventory_item_events (
    id           BIGINT       NOT NULL AUTO_INCREMENT,
    inventory_id BIGINT       NOT NULL,
    action       VARCHAR(16)  NOT NULL,
    sku          CHAR(8)      NOT NULL,
    name         VARCHAR(200) NOT NULL,
    quantity     INT          NOT NULL DEFAULT 0,
    operator_id  BIGINT       NOT NULL,
    created_at   DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_item_events_inventory_created (inventory_id, created_at),
    KEY idx_item_events_created (created_at),
    KEY idx_item_events_operator (operator_id),
    CONSTRAINT fk_item_events_inventory FOREIGN KEY (inventory_id) REFERENCES inventory (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_item_events_operator FOREIGN KEY (operator_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_item_events_action CHECK (action IN ('CREATED', 'DELETED')),
    CONSTRAINT chk_item_events_quantity CHECK (quantity >= 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- A product is an item put on sale. The row is created the first time the item is listed, and
-- it keeps the same id for ever, so orders that were placed under it stay tied to it. Delisting
-- sets the status to UNLISTED, and listing again sets it back to LISTED. Name and price cannot
-- change while the product is LISTED: to change either, delist it and list it again. The
-- LISTED/UNLISTED pairing of the delisting columns is checked by the database.
CREATE TABLE products (
    id           BIGINT        NOT NULL AUTO_INCREMENT,
    inventory_id BIGINT        NOT NULL,
    name         VARCHAR(200)  NOT NULL,
    price        DECIMAL(12,2) NOT NULL,
    status       VARCHAR(16)   NOT NULL,
    listed_at    DATETIME(3)   NOT NULL,
    listed_by    BIGINT        NOT NULL,
    delisted_at  DATETIME(3)   NULL,
    delisted_by  BIGINT        NULL,
    created_at   DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at   DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_products_inventory UNIQUE (inventory_id),
    -- Serves the product page and its search by name.
    KEY idx_products_status_name (status, name),
    KEY idx_products_listed_by (listed_by),
    KEY idx_products_delisted_by (delisted_by),
    CONSTRAINT fk_products_inventory FOREIGN KEY (inventory_id) REFERENCES inventory (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_products_listed_by FOREIGN KEY (listed_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_products_delisted_by FOREIGN KEY (delisted_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_products_price CHECK (price >= 0),
    CONSTRAINT chk_products_status CHECK (status IN ('LISTED', 'UNLISTED')),
    CONSTRAINT chk_products_delisted CHECK (
        (status = 'LISTED' AND delisted_at IS NULL AND delisted_by IS NULL)
        OR (status = 'UNLISTED' AND delisted_at IS NOT NULL AND delisted_by IS NOT NULL)
    )
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- Append-only record of every listing and delisting: the product, its warehouse item, what the
-- name and price were at that moment, who did it, and when. No reason is asked for.
CREATE TABLE product_listing_events (
    id           BIGINT        NOT NULL AUTO_INCREMENT,
    product_id   BIGINT        NOT NULL,
    inventory_id BIGINT        NOT NULL,
    action       VARCHAR(16)   NOT NULL,
    name         VARCHAR(200)  NOT NULL,
    price        DECIMAL(12,2) NOT NULL,
    operator_id  BIGINT        NOT NULL,
    created_at   DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_product_events_product_created (product_id, created_at),
    KEY idx_product_events_created (created_at),
    KEY idx_product_events_inventory (inventory_id),
    KEY idx_product_events_operator (operator_id),
    CONSTRAINT fk_product_events_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_product_events_inventory FOREIGN KEY (inventory_id) REFERENCES inventory (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_product_events_operator FOREIGN KEY (operator_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_product_events_action CHECK (action IN ('LISTED', 'DELISTED')),
    CONSTRAINT chk_product_events_price CHECK (price >= 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- ---------------------------------------------------------------------------
-- Orders
-- ---------------------------------------------------------------------------

-- order_no, ticket_no, and idempotency_key use utf8mb4_0900_bin, so they are compared
-- exactly: 'Abc' and 'abc' are different values. Usernames, emails, SKUs, and role codes
-- keep the default case-insensitive, accent-insensitive collation.
-- order_no is 'ORD-' plus a random UUID without hyphens. ticket_no is 8 random characters from
-- A-Z and 0-9, shown to people and typed to name a ticket. Both are generated by the application,
-- and the unique keys are the final guard against a clash.

-- An order is completed the moment it is placed: its stock is deducted in the same transaction, so
-- there is no reservation, no confirmation step, no timeout, and no status. An order is final and
-- is never cancelled. A wrong order is corrected by a ticket and a manual stock change, and a new
-- order. created_at is the time the order was placed and completed.
CREATE TABLE orders (
    id              BIGINT        NOT NULL AUTO_INCREMENT,
    order_no        VARCHAR(64)   COLLATE utf8mb4_0900_bin NOT NULL,
    user_id         BIGINT        NOT NULL,
    total_amount    DECIMAL(14,2) NOT NULL DEFAULT 0,
    item_count      INT           NOT NULL DEFAULT 0,
    idempotency_key VARCHAR(128)  COLLATE utf8mb4_0900_bin NULL,
    remark          VARCHAR(500)  NULL,
    created_at      DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at      DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_orders_order_no UNIQUE (order_no),
    -- Unique per user, not global. Rows without a key are not constrained.
    CONSTRAINT uk_orders_user_idempotency UNIQUE (user_id, idempotency_key),
    KEY idx_orders_user_created (user_id, created_at),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_orders_total_amount CHECK (total_amount >= 0),
    CONSTRAINT chk_orders_item_count CHECK (item_count >= 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- Order items are frozen after the order is created: no updated_at, and the service
-- layer must not edit or delete them. product_sku, product_name, and unit_price are copied at
-- order time (the sku from the warehouse item, the name and price from the product), so a later
-- change of either never touches an order.
CREATE TABLE order_items (
    id           BIGINT        NOT NULL AUTO_INCREMENT,
    order_id     BIGINT        NOT NULL,
    product_id   BIGINT        NOT NULL,
    product_sku  VARCHAR(64)   NOT NULL,
    product_name VARCHAR(200)  NOT NULL,
    unit_price   DECIMAL(12,2) NOT NULL,
    quantity     INT           NOT NULL,
    subtotal     DECIMAL(14,2) NOT NULL,
    created_at   DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_order_items_order_product UNIQUE (order_id, product_id),
    KEY idx_order_items_product (product_id),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT chk_order_items_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_order_items_subtotal CHECK (subtotal >= 0 AND subtotal = unit_price * quantity)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- Append-only record of every attempt to place an order, successful or not: who, when, which
-- product (product_name is its name at the time of the attempt, so the record stays readable if the
-- product is later listed under another name), how many, the result, and how much stock was deducted. One row for each product line of
-- an attempt. Every attempt has an order number, and a completed attempt carries the number of its
-- order. A completed row is written in the transaction of the order; a refused row is written in a
-- short transaction of its own after the order transaction rolled back, so a refusal leaves a record
-- and nothing else. quantity is the quantity as sent when it is a whole number that fits the column,
-- and 0 otherwise, so INVALID_QUANTITY rows may hold any value. A repeated submission with the same
-- idempotency key returns the original order and adds no row.
CREATE TABLE order_attempts (
    id             BIGINT       NOT NULL AUTO_INCREMENT,
    order_no       VARCHAR(64)  COLLATE utf8mb4_0900_bin NOT NULL,
    user_id        BIGINT       NOT NULL,
    product_id     BIGINT       NOT NULL,
    product_name   VARCHAR(200) NOT NULL,
    order_id       BIGINT       NULL,
    quantity       INT          NOT NULL,
    result         VARCHAR(32)  NOT NULL,
    stock_deducted INT          NOT NULL DEFAULT 0,
    created_at     DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_order_attempts_order_no_product UNIQUE (order_no, product_id),
    KEY idx_order_attempts_product_created (product_id, created_at),
    KEY idx_order_attempts_user_created (user_id, created_at),
    KEY idx_order_attempts_order (order_id),
    KEY idx_order_attempts_created (created_at),
    CONSTRAINT fk_order_attempts_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_order_attempts_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_order_attempts_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_order_attempts_result CHECK (result IN ('COMPLETED', 'PRODUCT_DELISTED', 'PRODUCT_CHANGED', 'OUT_OF_STOCK', 'INVALID_QUANTITY', 'BUSY')),
    -- A completed attempt has its order and deducted exactly what it ordered. A refused attempt has
    -- no order and deducted nothing.
    CONSTRAINT chk_order_attempts_outcome CHECK (
        (result = 'COMPLETED' AND order_id IS NOT NULL AND quantity > 0 AND stock_deducted = quantity)
        OR (result <> 'COMPLETED' AND order_id IS NULL AND stock_deducted = 0))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- Append-only. order_id is required for SALE and must be empty for the other types.
-- The unique key does not apply to rows with an empty order_id, so repeated restocks are
-- allowed, while one order can be sold once per item. The snapshots must agree
-- with the type and quantity. Every row names the user who caused it. The manual types
-- (RESTOCK, WRITE_OFF, ADJUST_IN, ADJUST_OUT) must also give a non-blank reason.
CREATE TABLE inventory_transactions (
    id               BIGINT       NOT NULL AUTO_INCREMENT,
    inventory_id     BIGINT       NOT NULL,
    order_id         BIGINT       NULL,
    operator_id      BIGINT       NOT NULL,
    type             VARCHAR(32)  NOT NULL,
    quantity         INT          NOT NULL,
    available_before INT          NOT NULL,
    available_after  INT          NOT NULL,
    reason           VARCHAR(255) NULL,
    created_at       DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_inventory_tx_order_inventory_type UNIQUE (order_id, inventory_id, type),
    KEY idx_inventory_tx_inventory_created (inventory_id, created_at),
    KEY idx_inventory_tx_created (created_at),
    KEY idx_inventory_tx_operator (operator_id),
    CONSTRAINT fk_inventory_tx_inventory FOREIGN KEY (inventory_id) REFERENCES inventory (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_inventory_tx_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_inventory_tx_operator FOREIGN KEY (operator_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_inventory_tx_type CHECK (type IN ('RESTOCK', 'WRITE_OFF', 'ADJUST_IN', 'ADJUST_OUT', 'SALE')),
    CONSTRAINT chk_inventory_tx_quantity CHECK (quantity > 0),
    CONSTRAINT chk_inventory_tx_manual CHECK (
        type = 'SALE'
        OR (reason IS NOT NULL AND CHAR_LENGTH(TRIM(reason)) > 0)
    ),
    CONSTRAINT chk_inventory_tx_snapshots CHECK (available_before >= 0 AND available_after >= 0),
    CONSTRAINT chk_inventory_tx_order_required CHECK (
        (type = 'SALE') = (order_id IS NOT NULL)
    ),
    CONSTRAINT chk_inventory_tx_movement CHECK ((
        CASE type
            WHEN 'RESTOCK'    THEN available_after = available_before + quantity
            WHEN 'WRITE_OFF'  THEN available_after = available_before - quantity
            WHEN 'ADJUST_IN'  THEN available_after = available_before + quantity
            WHEN 'ADJUST_OUT' THEN available_after = available_before - quantity
            WHEN 'SALE'       THEN available_after = available_before - quantity
            ELSE FALSE
        END
    ) = 1)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- ---------------------------------------------------------------------------
-- Tickets
-- ---------------------------------------------------------------------------

-- Status flow (enforced in the service layer, not by CHECK constraints):
--   OPEN is the pool of tickets nobody holds, and it never has an assignee.
--   Taking or being assigned a ticket makes it IN_PROGRESS at once, with the assignee.
--   IN_PROGRESS -> OPEN when the assignee is released or the assignee account is no longer usable.
--   IN_PROGRESS -> RESOLVED -> CLOSED (CLOSED means archived), and
--   OPEN or IN_PROGRESS -> CANCELLED. A ticket is never reopened. CLOSED and CANCELLED are final.
-- There is no priority. source says where a ticket came from, SYSTEM or MANUAL. It is set when
-- the ticket is created and never changed. A SYSTEM ticket is one the program opened, and its
-- created_by is the SYSTEM user (users.is_system). The service layer keeps the two in step,
-- because a CHECK cannot look at another table. The screen may use it, for example for the
-- background colour. An ORDER_EXCEPTION ticket must name an order number, which is the number of an
-- order attempt in order_attempts, a placed order or a refused one. order_no is a plain column and not a
-- foreign key, because the number is shared by the product lines of an attempt and so is not unique
-- there; the service layer checks that the attempt exists when the ticket is created, and attempts
-- are append-only and never deleted.
-- The ticket lists show SYSTEM tickets before MANUAL ones, then the chosen time order, so
-- their indexes lead with status and source. idx_tickets_status_resolved serves the archive job.
-- follows_ticket_id marks a new ticket as the continuation of an earlier one. It is set when
-- the ticket is created and never changed. ticket_inventory links are written only when the
-- ticket is created, in the same transaction.
CREATE TABLE tickets (
    id                BIGINT       NOT NULL AUTO_INCREMENT,
    ticket_no         CHAR(8)      COLLATE utf8mb4_0900_bin NOT NULL,
    order_no          VARCHAR(64)  COLLATE utf8mb4_0900_bin NULL,
    follows_ticket_id BIGINT       NULL,
    created_by        BIGINT       NOT NULL,
    assignee_id       BIGINT       NULL,
    resolved_by       BIGINT       NULL,
    closed_by         BIGINT       NULL,
    cancelled_by      BIGINT       NULL,
    type              VARCHAR(32)  NOT NULL,
    source            VARCHAR(16)  NOT NULL,
    status            VARCHAR(32)  NOT NULL DEFAULT 'OPEN',
    title             VARCHAR(200) NOT NULL,
    description       TEXT         NOT NULL,
    resolution        TEXT         NULL,
    cancel_reason     VARCHAR(255) NULL,
    resolved_at       DATETIME(3)  NULL,
    closed_at         DATETIME(3)  NULL,
    cancelled_at      DATETIME(3)  NULL,
    created_at        DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at        DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_tickets_ticket_no UNIQUE (ticket_no),
    CONSTRAINT chk_tickets_ticket_no CHECK (REGEXP_LIKE(ticket_no, '^[A-Z0-9]{8}$', 'c')),
    KEY idx_tickets_order_status (order_no, status),
    KEY idx_tickets_follows (follows_ticket_id),
    KEY idx_tickets_created_status (created_by, status),
    KEY idx_tickets_assignee_status (assignee_id, status),
    KEY idx_tickets_resolved_by (resolved_by),
    KEY idx_tickets_closed_by (closed_by),
    KEY idx_tickets_cancelled_by (cancelled_by),
    KEY idx_tickets_status_resolved (status, resolved_at),
    KEY idx_tickets_status_source_created (status, source, created_at),
    KEY idx_tickets_status_source_closed (status, source, closed_at),
    KEY idx_tickets_status_source_cancelled (status, source, cancelled_at),
    CONSTRAINT fk_tickets_follows FOREIGN KEY (follows_ticket_id) REFERENCES tickets (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_tickets_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_tickets_assignee FOREIGN KEY (assignee_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_tickets_resolved_by FOREIGN KEY (resolved_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_tickets_closed_by FOREIGN KEY (closed_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_tickets_cancelled_by FOREIGN KEY (cancelled_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_tickets_type CHECK (type IN ('ORDER_EXCEPTION', 'INVENTORY_EXCEPTION', 'OTHER')),

-- Append-only. from_user_id is empty for the first assignment, and to_user_id is empty
-- when a ticket is unassigned.
CREATE TABLE ticket_assignment_history (
    id           BIGINT       NOT NULL AUTO_INCREMENT,
    ticket_id    BIGINT       NOT NULL,
    from_user_id BIGINT       NULL,
    to_user_id   BIGINT       NULL,
    changed_by   BIGINT       NOT NULL,
    reason       VARCHAR(255) NULL,
    created_at   DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_ticket_assignment_ticket_created (ticket_id, created_at),
    KEY idx_ticket_assignment_from (from_user_id),
    KEY idx_ticket_assignment_to (to_user_id),
    KEY idx_ticket_assignment_changed_by (changed_by),
    CONSTRAINT fk_ticket_assignment_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_ticket_assignment_from FOREIGN KEY (from_user_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_ticket_assignment_to FOREIGN KEY (to_user_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_ticket_assignment_changed_by FOREIGN KEY (changed_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,

-- OpsFlow initial schema (matches database design v1.9)
--
-- Source of truth: docs/database/database-design.md
-- Target: MySQL 8.0.16 or later (CHECK constraints are enforced from 8.0.16).
-- Time zone: all DATETIME(3) values are stored in UTC. DATETIME carries no time zone,
-- and the defaults below use CURRENT_TIMESTAMP(3), which follows the session time zone.
-- Every connection must therefore set its session time zone to UTC: use the JDBC
-- parameters connectionTimeZone=UTC&forceConnectionTimeZoneToSession=true, and run
-- SET time_zone = '+00:00'; before any manual SQL that involves time.
-- History: foreign keys use ON DELETE RESTRICT so history rows are never cascaded or
-- nulled out. Users are soft-deleted (`deleted`), never physically deleted. Products are listed
-- and delisted, and are never deleted.
-- Data: this migration creates structure only. Roles and other seed data are added by
-- later migrations.
--
-- Do not edit this file after it has been applied to any database. Add a new
-- migration instead.

-- ---------------------------------------------------------------------------
-- Identity and access
-- ---------------------------------------------------------------------------

-- is_system marks the one built-in SYSTEM identity, which is recorded as the creator of
-- tickets the program opens by itself and as the one who acts for the program on tickets.
-- It is never a person: it has no role, cannot log in, and cannot be edited, disabled, or
-- deleted. A seed migration creates it; this migration creates structure only.
CREATE TABLE users (
    id                   BIGINT       NOT NULL AUTO_INCREMENT,
    username             VARCHAR(64)  NOT NULL,
    password_hash        VARCHAR(255) NOT NULL,
    password_changed_at  DATETIME(3)  NULL,
    email                VARCHAR(254) NOT NULL,
    username_changed_at  DATETIME(3)  NULL,
    email_changed_at     DATETIME(3)  NULL,
    status               VARCHAR(32)  NOT NULL DEFAULT 'ACTIVE',
    deleted              BOOLEAN      NOT NULL DEFAULT FALSE,
    is_system            BOOLEAN      NOT NULL DEFAULT FALSE,
    last_login_at        DATETIME(3)  NULL,
    failed_login_count   INT          NOT NULL DEFAULT 0,
    last_failed_login_at DATETIME(3)  NULL,
    locked_until         DATETIME(3)  NULL,
    created_at           DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at           DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT chk_users_status CHECK (status IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT chk_users_failed_login_count CHECK (failed_login_count >= 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE roles (
    id          BIGINT       NOT NULL AUTO_INCREMENT,

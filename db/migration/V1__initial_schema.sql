-- OpsFlow initial schema (database design v1.2)
--
-- Source of truth: docs/database/database-design.md
-- Target: MySQL 8.0.16 or later (CHECK constraints are enforced from 8.0.16).
-- Time zone: all DATETIME(3) values are stored in UTC. DATETIME carries no time zone,
-- and the defaults below use CURRENT_TIMESTAMP(3), which follows the session time zone.
-- Every connection must therefore set its session time zone to UTC: use the JDBC
-- parameters connectionTimeZone=UTC&forceConnectionTimeZoneToSession=true, and run
-- SET time_zone = '+00:00'; before any manual SQL that involves time.
-- History: foreign keys use ON DELETE RESTRICT so history rows are never cascaded or
-- nulled out. Users and products are soft-deleted (`deleted`), never physically deleted.
-- Data: this migration creates structure only. Roles and other seed data are added by
-- later migrations.
--
-- Do not edit this file after it has been applied to any database. Add a new
-- migration instead.

-- ---------------------------------------------------------------------------
-- Identity and access
-- ---------------------------------------------------------------------------

CREATE TABLE users (
    id            BIGINT       NOT NULL AUTO_INCREMENT,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    email         VARCHAR(254) NOT NULL,
    status        VARCHAR(32)  NOT NULL DEFAULT 'ACTIVE',
    deleted       BOOLEAN      NOT NULL DEFAULT FALSE,
    last_login_at DATETIME(3)  NULL,
    created_at    DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at    DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT chk_users_status CHECK (status IN ('ACTIVE', 'DISABLED'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE roles (
    id          BIGINT       NOT NULL AUTO_INCREMENT,
    code        VARCHAR(32)  NOT NULL,
    name        VARCHAR(64)  NOT NULL,
    description VARCHAR(255) NULL,
    created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_roles_code UNIQUE (code)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

CREATE TABLE user_roles (
    id         BIGINT      NOT NULL AUTO_INCREMENT,
    user_id    BIGINT      NOT NULL,
    role_id    BIGINT      NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_user_roles_user_role UNIQUE (user_id, role_id),
    KEY idx_user_roles_role (role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- ---------------------------------------------------------------------------
-- Product and inventory
-- ---------------------------------------------------------------------------

CREATE TABLE products (
    id          BIGINT        NOT NULL AUTO_INCREMENT,
    sku         VARCHAR(64)   NOT NULL,
    name        VARCHAR(200)  NOT NULL,
    description TEXT          NULL,
    price       DECIMAL(12,2) NOT NULL,
    status      VARCHAR(32)   NOT NULL DEFAULT 'ACTIVE',
    deleted     BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at  DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_products_sku UNIQUE (sku),
    CONSTRAINT chk_products_price CHECK (price >= 0),
    CONSTRAINT chk_products_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- Stock is changed only under pessimistic row locking (SELECT ... FOR UPDATE), so this
-- table has no version column.
CREATE TABLE inventory (
    id                 BIGINT      NOT NULL AUTO_INCREMENT,
    product_id         BIGINT      NOT NULL,
    available_quantity INT         NOT NULL DEFAULT 0,
    locked_quantity    INT         NOT NULL DEFAULT 0,
    sold_quantity      INT         NOT NULL DEFAULT 0,
    created_at         DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at         DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_inventory_product UNIQUE (product_id),
    CONSTRAINT fk_inventory_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_inventory_available CHECK (available_quantity >= 0),
    CONSTRAINT chk_inventory_locked CHECK (locked_quantity >= 0),
    CONSTRAINT chk_inventory_sold CHECK (sold_quantity >= 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- ---------------------------------------------------------------------------
-- Orders
-- ---------------------------------------------------------------------------

-- order_no, ticket_no, and idempotency_key use utf8mb4_0900_bin, so they are compared
-- exactly: 'Abc' and 'abc' are different values. Usernames, emails, SKUs, and role codes
-- keep the default case-insensitive, accent-insensitive collation.
-- order_no is 'ORD-' plus a random UUID without hyphens, and ticket_no is 'TKT-' plus the
-- same, generated by the application. The unique keys are the final guard against a clash.

CREATE TABLE orders (
    id              BIGINT        NOT NULL AUTO_INCREMENT,
    order_no        VARCHAR(64)   COLLATE utf8mb4_0900_bin NOT NULL,
    user_id         BIGINT        NOT NULL,
    status          VARCHAR(32)   NOT NULL DEFAULT 'CREATED',
    total_amount    DECIMAL(14,2) NOT NULL DEFAULT 0,
    item_count      INT           NOT NULL DEFAULT 0,
    idempotency_key VARCHAR(128)  COLLATE utf8mb4_0900_bin NULL,
    reserved_until  DATETIME(3)   NOT NULL,
    status_reason   VARCHAR(255)  NULL,
    finished_at     DATETIME(3)   NULL,
    remark          VARCHAR(500)  NULL,
    created_at      DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at      DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_orders_order_no UNIQUE (order_no),
    -- Unique per user, not global. Rows without a key are not constrained.
    CONSTRAINT uk_orders_user_idempotency UNIQUE (user_id, idempotency_key),
    -- Serves the reservation timeout job.
    KEY idx_orders_status_reserved_until (status, reserved_until),
    KEY idx_orders_user_created (user_id, created_at),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_orders_status CHECK (status IN ('CREATED', 'COMPLETED', 'CANCELLED', 'FAILED')),
    CONSTRAINT chk_orders_total_amount CHECK (total_amount >= 0),
    CONSTRAINT chk_orders_item_count CHECK (item_count >= 0),
    -- CREATED is the only non-final status, and finished_at is set exactly when an
    -- order reaches a final status.
    CONSTRAINT chk_orders_finished CHECK (
        (status = 'CREATED' AND finished_at IS NULL)
        OR (status <> 'CREATED' AND finished_at IS NOT NULL)
    )
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- Order items are frozen after the order is created: no updated_at, and the service
-- layer must not edit or delete them.
CREATE TABLE order_items (
    id           BIGINT        NOT NULL AUTO_INCREMENT,
    order_id     BIGINT        NOT NULL,
    product_id   BIGINT        NOT NULL,
    product_sku  VARCHAR(64)   NOT NULL,
    product_name VARCHAR(200)  NOT NULL,
    unit_price   DECIMAL(12,2) NOT NULL,
    quantity     INT           NOT NULL,
    subtotal     DECIMAL(14,2) NOT NULL,
    created_at   DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_order_items_order_product UNIQUE (order_id, product_id),
    KEY idx_order_items_product (product_id),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT chk_order_items_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_order_items_subtotal CHECK (subtotal >= 0 AND subtotal = unit_price * quantity)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- Append-only. order_id is required for RESERVE, CONFIRM, and RELEASE and must be empty
-- for the other types. The unique key does not apply to rows with an empty order_id, so
-- repeated restocks are allowed. The snapshots must agree with the type and quantity.
CREATE TABLE inventory_transactions (
    id               BIGINT       NOT NULL AUTO_INCREMENT,
    inventory_id     BIGINT       NOT NULL,
    order_id         BIGINT       NULL,
    operator_id      BIGINT       NULL,
    type             VARCHAR(32)  NOT NULL,
    quantity         INT          NOT NULL,
    available_before INT          NOT NULL,
    available_after  INT          NOT NULL,
    locked_before    INT          NOT NULL,
    locked_after     INT          NOT NULL,
    reason           VARCHAR(255) NULL,
    created_at       DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_inventory_tx_order_inventory_type UNIQUE (order_id, inventory_id, type),
    KEY idx_inventory_tx_inventory_created (inventory_id, created_at),
    KEY idx_inventory_tx_operator (operator_id),
    CONSTRAINT fk_inventory_tx_inventory FOREIGN KEY (inventory_id) REFERENCES inventory (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_inventory_tx_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_inventory_tx_operator FOREIGN KEY (operator_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_inventory_tx_type CHECK (type IN ('RESTOCK', 'ADJUST_IN', 'ADJUST_OUT', 'RESERVE', 'CONFIRM', 'RELEASE')),
    CONSTRAINT chk_inventory_tx_quantity CHECK (quantity > 0),
    CONSTRAINT chk_inventory_tx_snapshots CHECK (
        available_before >= 0 AND available_after >= 0 AND locked_before >= 0 AND locked_after >= 0
    ),
    CONSTRAINT chk_inventory_tx_order_required CHECK (
        (type IN ('RESERVE', 'CONFIRM', 'RELEASE')) = (order_id IS NOT NULL)
    ),
    CONSTRAINT chk_inventory_tx_movement CHECK ((
        CASE type
            WHEN 'RESTOCK'    THEN available_after = available_before + quantity AND locked_after = locked_before
            WHEN 'ADJUST_IN'  THEN available_after = available_before + quantity AND locked_after = locked_before
            WHEN 'ADJUST_OUT' THEN available_after = available_before - quantity AND locked_after = locked_before
            WHEN 'RESERVE'    THEN available_after = available_before - quantity AND locked_after = locked_before + quantity
            WHEN 'CONFIRM'    THEN available_after = available_before AND locked_after = locked_before - quantity
            WHEN 'RELEASE'    THEN available_after = available_before + quantity AND locked_after = locked_before - quantity
            ELSE FALSE
        END
    ) = 1)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- ---------------------------------------------------------------------------
-- Tickets
-- ---------------------------------------------------------------------------

CREATE TABLE tickets (
    id          BIGINT       NOT NULL AUTO_INCREMENT,
    ticket_no   VARCHAR(64)  COLLATE utf8mb4_0900_bin NOT NULL,
    order_id    BIGINT       NULL,
    created_by  BIGINT       NOT NULL,
    assignee_id BIGINT       NULL,
    resolved_by BIGINT       NULL,
    type        VARCHAR(32)  NOT NULL,
    priority    VARCHAR(32)  NOT NULL,
    status      VARCHAR(32)  NOT NULL DEFAULT 'OPEN',
    title       VARCHAR(200) NOT NULL,
    description TEXT         NOT NULL,
    resolution  TEXT         NULL,
    resolved_at DATETIME(3)  NULL,
    closed_at   DATETIME(3)  NULL,
    created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    CONSTRAINT uk_tickets_ticket_no UNIQUE (ticket_no),
    KEY idx_tickets_order (order_id),
    KEY idx_tickets_created_by (created_by),
    KEY idx_tickets_assignee_status (assignee_id, status),
    KEY idx_tickets_resolved_by (resolved_by),
    KEY idx_tickets_status_priority (status, priority),
    CONSTRAINT fk_tickets_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_tickets_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_tickets_assignee FOREIGN KEY (assignee_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_tickets_resolved_by FOREIGN KEY (resolved_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT chk_tickets_type CHECK (type IN ('ORDER_EXCEPTION', 'INVENTORY_EXCEPTION', 'OTHER')),
    CONSTRAINT chk_tickets_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    CONSTRAINT chk_tickets_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED'))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- Append-only. from_user_id is empty for the first assignment, and to_user_id is empty
-- when a ticket is unassigned.
CREATE TABLE ticket_assignment_history (
    id           BIGINT       NOT NULL AUTO_INCREMENT,
    ticket_id    BIGINT       NOT NULL,
    from_user_id BIGINT       NULL,
    to_user_id   BIGINT       NULL,
    changed_by   BIGINT       NOT NULL,
    reason       VARCHAR(255) NULL,
    created_at   DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_ticket_assignment_ticket_created (ticket_id, created_at),
    KEY idx_ticket_assignment_from (from_user_id),
    KEY idx_ticket_assignment_to (to_user_id),
    KEY idx_ticket_assignment_changed_by (changed_by),
    CONSTRAINT fk_ticket_assignment_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_ticket_assignment_from FOREIGN KEY (from_user_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_ticket_assignment_to FOREIGN KEY (to_user_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_ticket_assignment_changed_by FOREIGN KEY (changed_by) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    -- An assignment record must actually change the assignee.
    CONSTRAINT chk_ticket_assignment_changed CHECK (NOT (from_user_id <=> to_user_id))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- Append-only: comments are never edited or deleted, so there is no updated_at. A mistake
-- is corrected by adding a new comment.
CREATE TABLE ticket_comments (
    id         BIGINT      NOT NULL AUTO_INCREMENT,
    ticket_id  BIGINT      NOT NULL,
    user_id    BIGINT      NOT NULL,
    content    TEXT        NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_ticket_comments_ticket_created (ticket_id, created_at),
    KEY idx_ticket_comments_user (user_id),
    CONSTRAINT fk_ticket_comments_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_ticket_comments_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;

-- ---------------------------------------------------------------------------
-- Auditing
-- ---------------------------------------------------------------------------

-- Append-only. (target_type, target_id) is a polymorphic reference maintained by the
-- application, so it has no foreign key. operator_id is empty for system actions.
CREATE TABLE operation_logs (
    id          BIGINT       NOT NULL AUTO_INCREMENT,
    operator_id BIGINT       NULL,
    action      VARCHAR(64)  NOT NULL,
    target_type VARCHAR(64)  NOT NULL,
    target_id   BIGINT       NOT NULL,
    before_data JSON         NULL,
    after_data  JSON         NULL,
    ip_address  VARCHAR(45)  NULL,
    remark      VARCHAR(500) NULL,
    created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_operation_logs_target (target_type, target_id),
    KEY idx_operation_logs_operator_created (operator_id, created_at),
    CONSTRAINT fk_operation_logs_operator FOREIGN KEY (operator_id) REFERENCES users (id) ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4;
